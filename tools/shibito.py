#!/usr/bin/env python3
"""shibito - analysis toolkit for the SCUS-97355 executable.

  python tools/shibito.py verify            check ELF hash
  python tools/shibito.py info              ELF header / segments / SDK libs
  python tools/shibito.py syscalls          kernel syscall wrappers found in the ELF
  python tools/shibito.py report            write PUBLIC-safe samples  -> analysis/ symbols/ stubs/
  python tools/shibito.py report --full     write FULL dumps (private) -> dev/
  python tools/shibito.py check-public DIR  fail if DIR contains game data
"""
from __future__ import annotations

import argparse
import codecs
import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze          # noqa: E402
import elfkit           # noqa: E402

ROOT = elfkit.ROOT
PRIV = ROOT / "private"
CONFIG = json.loads((ROOT / "config" / "game.json").read_text())
ELF = PRIV / CONFIG["elf_name"]
CSRC = PRIV / (CONFIG["elf_name"] + ".c")


def need(p: Path):
    if not p.exists():
        sys.exit(f"missing {p.relative_to(ROOT)} - see private/README.md")


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))


# ------------------------------------------------------------------ verify
def cmd_verify(_a):
    need(ELF)
    got = elfkit.parse_elf(ELF).sha256
    ok = got == CONFIG["sha256"]
    print(("OK  " if ok else "FAIL"), got)
    return 0 if ok else 1


# -------------------------------------------------------------------- info
def info_dict(elf):
    c = elf.code
    return {
        "game_id": CONFIG["game_id"], "region": CONFIG["region"],
        "sha256": elf.sha256, "size": len(elf.data),
        "entry": f"0x{elf.entry:08X}",
        "machine": "MIPS (R5900 / EE)", "abi_flags": f"0x{elf.flags:08X}",
        "code_load": f"0x{c.vaddr:08X}", "code_size": f"0x{c.filesz:X}",
        "mem_end": f"0x{c.vaddr + c.memsz:08X}",
        "bss_size": f"0x{c.memsz - c.filesz:X}",
        "compiler": elf.comment, "stripped": not any(
            s.get("name") == ".symtab" and s["size"] for s in elf.sections),
        "sdk_libs": elfkit.detect_sdk_libs(elf),
    }


def cmd_info(_a):
    need(ELF)
    print(json.dumps(info_dict(elfkit.parse_elf(ELF)), indent=2))


def cmd_syscalls(_a):
    need(ELF)
    w = elfkit.scan_syscalls(elfkit.parse_elf(ELF))
    print("addr       num  wrapper  name")
    for x in w:
        print(f"0x{x['addr']:08X} {x['number']:>4}  {'yes' if x['wrapper'] else 'no ':7}  {x['name']}")
    print(f"\n{len(w)} sites, {sum(x['wrapper'] for x in w)} wrappers, "
          f"{sum(x['known'] for x in w)} with known names")


# ------------------------------------------------------------------ report
def csv_rows(rows):
    for r in rows:
        yield [f"0x{r.addr:08X}", r.name, r.kind, f"0x{r.span:X}", r.callers,
               "" if r.syscall is None else r.syscall]


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["address", "name", "kind", "span", "callers", "syscall"])
        w.writerows(csv_rows(rows))
    print("wrote", path.relative_to(ROOT))


def symbols_txt(rows):
    out = ["# name = address;  // span (callers)\n"]
    for r in rows:
        out.append(f"{r.name} = 0x{r.addr:08X}; // span:0x{r.span:X} callers:{r.callers}\n")
    return "".join(out)


def stub_c(rows, title):
    out = [f"/* {title}\n * Signatures only - no game code. Generated by tools/shibito.py.\n */\n",
           '#include "types.h"\n\n']
    for r in rows:
        f = r.func
        body = "" if f.ret == "void" else "\n    return 0;"
        out.append(f"/* 0x{r.addr:08X}  span:0x{r.span:X}  callers:{r.callers} */\n"
                   f"{f.ret} {r.name}({f.params})\n{{\n    /* TODO */{body}\n}}\n\n")
    return "".join(out).rstrip() + "\n"


def report_md(model, info):
    rows, cov = model["rows"], analyze.coverage(model)
    kinds = Counter(r.kind for r in rows)
    buckets = Counter()
    for r in rows:
        buckets["<=0x40" if r.span <= 0x40 else "<=0x100" if r.span <= 0x100
                else "<=0x400" if r.span <= 0x400 else ">0x400"] += 1
    hot = sorted(rows, key=lambda r: -r.callers)[:15]
    md = [f"# Analysis report - {info['game_id']}\n\n",
          "Generated by `tools/shibito.py report`. Metadata only.\n\n",
          "## Executable\n\n| Field | Value |\n|---|---|\n"]
    for k in ("sha256", "size", "entry", "machine", "code_load", "code_size", "mem_end",
              "bss_size", "stripped"):
        md.append(f"| {k} | `{info[k]}` |\n")
    md.append(f"| compiler | `{' / '.join(info['compiler'])}` |\n")
    md.append("\n## SDK libraries (from library-owned strings)\n\n")
    md.append(", ".join(f"`{k}` ({v})" for k, v in sorted(info["sdk_libs"].items())) + "\n")
    md.append("\n## Functions\n\n| Kind | Count |\n|---|---|\n")
    for k, v in sorted(kinds.items()):
        md.append(f"| {k} | {v} |\n")
    md.append(f"| **total** | **{len(rows)}** |\n\n")
    md.append("Span buckets: " + ", ".join(f"`{k}` {v}" for k, v in sorted(buckets.items())) + "\n\n")
    md.append(f"Direct `jal` targets: {cov['jal_targets']} "
              f"({cov['targets_in_ghidra']} match a known function, "
              f"{100 * cov['targets_in_ghidra'] // max(1, cov['jal_targets'])}%).\n\n")
    md.append("## Most-called functions\n\n| Address | Name | Callers | Span |\n|---|---|---|---|\n")
    for r in hot:
        md.append(f"| `0x{r.addr:08X}` | `{r.name}` | {r.callers} | `0x{r.span:X}` |\n")
    sc = [w for w in model["wrappers"] if w["known"]]
    md.append(f"\n## Kernel syscall wrappers\n\n{len(model['wrappers'])} wrappers found "
              f"in the ELF, {len(sc)} map to a known EE kernel name "
              "(full list: `analysis/syscalls.csv`).\n")
    return "".join(md)


def cmd_report(a):
    need(ELF)
    need(CSRC)
    model = analyze.build(ELF, CSRC)
    elf = model["elf"]
    info = info_dict(elf)
    rows = model["rows"]

    if a.full:
        out = ROOT / "dev"
        write_csv(out / "functions_full.csv", rows)
        write(out / "symbols_full.txt", symbols_txt(rows))
        write(out / "stubs_all.c", stub_c([r for r in rows if r.func.stub_safe],
                                          "ALL stubs (private)"))
        write(out / "strings_full.txt", "".join(
            f"0x{a_:08X}  {t}\n" for a_, t in elfkit.scan_strings(elf)))
        return 0

    out = ROOT / "analysis"
    write(out / "elf_info.json", json.dumps(info, indent=2) + "\n")
    write(out / "report.md", report_md(model, info))
    sys_rows = sorted(model["wrappers"], key=lambda w: w["addr"])
    p = out / "syscalls.csv"
    with open(p, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["address", "number", "name", "known"])
        for x in sys_rows:
            w.writerow([f"0x{x['addr']:08X}", x["number"], x["name"], int(x["known"])])
    print("wrote", p.relative_to(ROOT))

    sample = analyze.pick_sample(model)
    write_csv(ROOT / "symbols" / "symbols_sample.csv", sample)
    write(ROOT / "symbols" / "symbols_sample.txt", symbols_txt(sample))
    stubs = analyze.pick_sample(model, n_unnamed=60, stub_only=True)
    write(ROOT / "stubs" / "stubs_sample.c", stub_c(stubs, "Sample stubs"))
    return 0


# ------------------------------------------------------------ check-public
BLOCK_EXT = {".elf", ".iso", ".bin", ".gzf", ".img", ".cue", ".mcd", ".irx", ".self"}
BLOCK_NAME = re.compile(r"^SCUS_\d{3}\.\d{2}", re.I)
MAX_SIZE = 1_000_000
GHIDRA_LOCALS = re.compile(r"\b(?:[iu]Var\d+|[iu]Stack_|in_[a-z]{2}_\w+|pcVar\d+)\b")


def cmd_check_public(a):
    root = Path(a.dir).resolve()
    banned = [codecs.decode(w, "rot13").lower() for w in CONFIG.get("banned_rot13", [])]
    bad = []
    for p in sorted(root.rglob("*")):
        if not p.is_file() or ".git" in p.parts:
            continue
        rel = p.relative_to(root)
        if p.suffix.lower() in BLOCK_EXT or BLOCK_NAME.match(p.name):
            bad.append(f"{rel}: blocked file type/name")
            continue
        if p.stat().st_size > MAX_SIZE:
            bad.append(f"{rel}: larger than {MAX_SIZE // 1000} KB")
        head = p.read_bytes()[:4]
        if head == b"\x7fELF":
            bad.append(f"{rel}: ELF binary")
            continue
        if p.suffix.lower() in {".png", ".jpg", ".jpeg", ".zip", ".gif"}:
            continue
        txt = p.read_text(encoding="utf-8", errors="ignore")
        if GHIDRA_LOCALS.search(txt) and p.suffix in {".c", ".h", ".txt", ".md"}:
            bad.append(f"{rel}: decompiler output (Ghidra locals)")
        low = txt.lower()
        for w in banned:
            if w in low:
                bad.append(f"{rel}: contains banned word '{w}'")
    if bad:
        print("PUBLIC CHECK FAILED")
        print("\n".join("  - " + b for b in bad))
        return 1
    print(f"public check OK ({root.name})")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("verify").set_defaults(fn=cmd_verify)
    sub.add_parser("info").set_defaults(fn=cmd_info)
    sub.add_parser("syscalls").set_defaults(fn=cmd_syscalls)
    r = sub.add_parser("report")
    r.add_argument("--full", action="store_true", help="private full dump -> dev/")
    r.set_defaults(fn=cmd_report)
    c = sub.add_parser("check-public")
    c.add_argument("dir", nargs="?", default=".")
    c.set_defaults(fn=cmd_check_public)
    a = ap.parse_args()
    sys.exit(a.fn(a) or 0)


if __name__ == "__main__":
    main()
